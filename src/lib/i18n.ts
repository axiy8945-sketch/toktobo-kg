export function t(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  const idx = lang === "uz" ? 1 : lang === "ru" ? 2 : 0;
  let s = D[key][idx] || D[key][0];
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

